function buildEasyRunWithStridesStreams(
  totalSec = 5280,
  totalDistKm = 16.4,
  basePaceSec = 322,
  basePower = 281,
  baseHr = 128
): ActivityStreamPoint[] {
  const points: ActivityStreamPoint[] = [];
  const stepSec = 30;
  const totalSteps = Math.floor(totalSec / stepSec);

  for (let i = 0; i <= totalSteps; i++) {
    const t = i * stepSec;
    const progress = i / totalSteps;
    const dist = Number((progress * totalDistKm).toFixed(2));

    const wave1 = Math.sin(i * 0.43);
    const wave2 = Math.cos(i * 0.71);

    let pace = basePaceSec + Math.round(wave1 * 4 + wave2 * 3);
    let watts = basePower + Math.round(-wave1 * 6 + wave2 * 5);
    let hr = baseHr + Math.round(wave1 * 3 + (progress > 0.15 ? 2 : -4));
    let cadence = 76 + (i % 5 === 0 ? 1 : 0);
    let alt = Number(
      (33.5 + Math.sin(progress * Math.PI * 2.2) * 2.8 + Math.cos(i * 0.25) * 0.9).toFixed(1)
    );
    if (i < 6) alt = Number((30.2 + i * 0.7).toFixed(1));

    if (i === 11 || i === 45 || i === 96) {
      pace = 545;
      watts = 35;
      hr = Math.max(88, hr - 32);
      cadence = i === 11 ? 0 : 48;
    } else if (i === 12 || i === 46 || i === 97) {
      hr = baseHr - 14;
    }

    const isStride = i === 155 || i === 158 || i === 161 || i === 164 || i === 167;
    if (isStride) {
      pace = 259;
      watts = 445 + (i % 3) * 18;
      hr = 138 + (i % 4);
      cadence = 81;
    }

    points.push({
      timeSec: t,
      distanceKm: dist,
      paceSecPerKm: pace,
      powerWatts: watts,
      heartRateBpm: hr,
      cadenceSpm: cadence,
      altitudeMeters: alt,
      zone: isStride ? 'Z3' : 'Z1',
    });
  }

  return points;
}

function buildUphillIntervalsStreams(): ActivityStreamPoint[] {
  const points: ActivityStreamPoint[] = [];
  const totalSec = 3660;
  const stepSec = 30;
  const totalSteps = Math.floor(totalSec / stepSec);

  for (let i = 0; i <= totalSteps; i++) {
    const t = i * stepSec;
    const progress = i / totalSteps;
    const dist = Number((progress * 13.0).toFixed(2));

    const inIntervalBlock = i >= 36 && i <= 96;
    const isWorkRep = inIntervalBlock && Math.floor((i - 36) / 4) % 2 === 0;

    const pace = isWorkRep ? 232 + (i % 3) * 3 : inIntervalBlock ? 310 : 272 + (i % 4) * 2;
    const watts = isWorkRep ? 438 + (i % 5) * 6 : inIntervalBlock ? 255 : 335;
    const hr = isWorkRep ? 166 + (i % 5) : inIntervalBlock ? 142 : 146;
    const cadence = isWorkRep ? 84 : 77;
    const alt = Number((42 + progress * 115 + Math.sin(i * 0.4) * 8).toFixed(1));

    points.push({
      timeSec: t,
      distanceKm: dist,
      paceSecPerKm: pace,
      powerWatts: watts,
      heartRateBpm: hr,
      cadenceSpm: cadence,
      altitudeMeters: alt,
      zone: isWorkRep ? 'Z4' : 'Z2',
    });
  }

  return points;
}

